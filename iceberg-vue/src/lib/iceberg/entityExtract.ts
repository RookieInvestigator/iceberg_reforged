function canonicalPlace(raw: string): string {
  const s = raw.trim()
  return PLACE_ALIAS[s] || s
}

export function extractPlaces(text: string): string[] {
  const found = new Set<string>()
  const add = (raw: string) => {
    const p = canonicalPlace(raw)
    if (!p || p.length < 2) return
    if (PLACE_CONTEXT_STOP.has(p)) return
    found.add(p)
  }

  // 先遮罩非地理专名复合词，并在长地名命中后把对应区间置空，防止子串误判
  let scanText = text.replace(NON_GEO_COMPOUND_RE, (m) => ' '.repeat(m.length))

  for (const place of KNOWN_PLACES) {
    if (scanText.includes(place)) {
      add(place)
      scanText = scanText.split(place).join(' '.repeat(place.length))
    }
  }

  PLACE_CONTEXT_RE.lastIndex = 0
  for (const m of scanText.matchAll(PLACE_CONTEXT_RE)) {
    const cand = m[1]
    if (!cand) continue
    if (/^(?:该|某|一|这|那|那个|这个|当地|我国|各|偏远)/.test(cand)) continue
    if (PLACE_CONTEXT_STOP.has(cand)) continue
    if (cand.startsWith('中国') && cand.length === 3) continue
    add(cand)
  }

  for (const [redundant, canonical] of PLACE_SUBSUME) {
    if (found.has(redundant) && found.has(canonical)) found.delete(redundant)
  }

  return [...found].slice(0, 8)
}


/** 将精确年份归并到 10 年代，供跨词条年代软关联与层级追溯 */
export function yearToDecade(yearToken: string): string | null {
  const m = /^(\d{4})年$/.exec(yearToken.trim())
  if (!m) return null
  const y = Number(m[1])
  if (y < 1000 || y > 2099) return null
  const dec = Math.floor(y / 10) * 10
  return `${dec}年代`
}

/** 细粒度时间标签的上位父时期（用于软关联降权匹配，兼顾细分类与同朝代关联） */
export function timeParentPeriod(token: string): string | null {
  const dec = yearToDecade(token)
  if (dec) return dec
  if (token.endsWith('年代初') || token.endsWith('年代中期') || token.endsWith('年代末')) {
    return token.replace(/(?:初|中期|末)$/, '')
  }
  const SUB_ERA_PARENT: Readonly<Record<string, string>> = {
    西汉: '汉代',
    东汉: '汉代',
    西晋: '魏晋时期',
    东晋: '魏晋时期',
    初唐: '唐代',
    盛唐: '唐代',
    中唐: '唐代',
    晚唐: '唐代',
    北宋: '宋代',
    南宋: '宋代',
    明初: '明代',
    明中叶: '明代',
    明末: '明代',
    清初: '清代',
    清中叶: '清代',
    清末: '清代',
    民国初年: '民国时期',
    春秋时期: '春秋战国',
    战国时期: '春秋战国',
  }
  if (SUB_ERA_PARENT[token]) return SUB_ERA_PARENT[token]!
  if (/^\d{2}世纪(?:初|中叶|中期|末|末期)$/.test(token)) {
    return token.replace(/(?:初|中叶|中期|末|末期)$/, '')
  }
  return null
}

export function extractTimes(text: string): string[] {
  const found = new Set<string>()

  // 1) 公元前精确年份
  for (const m of text.matchAll(/公元前\s*(\d{1,4})年/g)) {
    found.add(`公元前${m[1]}年`)
  }

  // 2) 公元后精确年份 (1000-2029年)
  for (const m of text.matchAll(/(?<![0-9前])(1[0-9]{3}|20[0-2][0-9])年/g)) {
    found.add(`${m[1]}年`)
  }

  // 3) 细粒度世纪分段（20世纪初 / 20世纪中叶 / 19世纪末）+ 整世纪
  for (const m of text.matchAll(/(1[4-9]|2[01])世纪(初|初期|中叶|中期|末|末期|下半叶|上半叶)?/g)) {
    const cent = `${m[1]}世纪`
    const mod = m[2]
    if (mod === '初' || mod === '初期' || mod === '上半叶') found.add(`${cent}初`)
    else if (mod === '中叶' || mod === '中期') found.add(`${cent}中叶`)
    else if (mod === '末' || mod === '末期' || mod === '下半叶') found.add(`${cent}末`)
    else found.add(cent)
  }

  // 4) 阿拉伯数字年代（支持细分：90年代初/中期/末）
  for (const m of text.matchAll(/(1[89]\d0|20[0-2]0)年代(初|初期|中期|末|末期)?/g)) {
    const base = `${m[1]}年代`
    if (m[2] === '初' || m[2] === '初期') found.add(`${base}初`)
    else if (m[2] === '中期') found.add(`${base}中期`)
    else if (m[2] === '末' || m[2] === '末期') found.add(`${base}末`)
    else found.add(base)
  }
  for (const m of text.matchAll(/(?:上个?世纪|20世纪|二十世纪)\s*([1-9])0年代(初|初期|中期|末|末期)?/g)) {
    const base = `19${m[1]}0年代`
    if (m[2] === '初' || m[2] === '初期') found.add(`${base}初`)
    else if (m[2] === '中期') found.add(`${base}中期`)
    else if (m[2] === '末' || m[2] === '末期') found.add(`${base}末`)
    else found.add(base)
  }
  for (const m of text.matchAll(/(?:21世纪|二十一世纪|本世纪)\s*(00|10|20)年代(初|中期|末)?/g)) {
    const base = `20${m[1]}年代`
    found.add(m[2] ? `${base}${m[2]}` : base)
  }
  for (const m of text.matchAll(/(?<![0-9世纪])([3-9])0年代(初|中期|末)?/g)) {
    const base = `19${m[1]}0年代`
    found.add(m[2] ? `${base}${m[2]}` : base)
  }
  for (const m of text.matchAll(/(?<![0-9世纪])00年代(初|中期|末)?/g)) {
    found.add(m[1] ? `2000年代${m[1]}` : '2000年代')
  }

  // 5) 中文数字年代（含初/中/末与双年代）
  for (const m of text.matchAll(/(?:上个?世纪|20世纪|二十世纪)?([二三四五六七八九])十年代(初|中期|末)?/g)) {
    const d = CN_DECADE_DIGIT[m[1]!]
    if (d) {
      const base = `19${d}0年代`
      found.add(m[2] ? `${base}${m[2]}` : base)
    }
  }
  if (/五六十年代/.test(text)) {
    found.add('1950年代')
    found.add('1960年代')
  }
  if (/七八十年代/.test(text)) {
    found.add('1970年代')
    found.add('1980年代')
  }
  if (/八九十年代/.test(text)) {
    found.add('1980年代')
    found.add('1990年代')
  }

  // 6) 细粒度历史分期、朝代与节令
  for (const [re, label] of FINE_ERA_PATTERNS) {
    re.lastIndex = 0
    if (re.test(text)) found.add(label)
  }

  // 7) 上位朝代并落：细分期（明初/清中叶…）再挂一个共同父朝代（明代/清代…），
  //    让「嘉靖」「永乐」这些不同年号在实体共现层能归到同一个「明」。
  //    wordGraph 侧另有 timeParentPeriod 软关联，这里直接落标签使两者一致。
  for (const label of [...found]) {
    const parent = timeParentPeriod(label)
    if (parent) found.add(parent)
  }

  return [...found].slice(0, 8)
}

